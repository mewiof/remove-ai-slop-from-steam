import { test } from "node:test";
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const {
	classify,
	NONE,
	MINOR,
	SOME,
	HEAVY,
} = require("../src/lib/classify.js");

// content_survey_ai_notes of store items (GetItems, 2026-10-22)
const real = JSON.parse(
	readFileSync(new URL("./disclosures.json", import.meta.url), "utf8"),
);

test("real disclosures get the level a person gave them", () => {
	const wrong = [];
	for (const d of real) {
		const got = classify(d.text);
		if (got.level !== d.level)
			wrong.push(
				`${d.appid}: want ${d.level} got ${got.level} (${got.kinds.join(",")})`,
			);
	}
	assert.deepEqual(wrong, []);
});

const cases = [
	["", NONE],
	["We used AI to help write some code.", MINOR],
	["AI translations for German and French.", MINOR],
	["This visual novel was translated with AI.", MINOR],
	[
		"No AI was used in the game itself, only to generate marketing images and logos.",
		MINOR,
	],
	["All AI-generated content was reviewed by our team.", MINOR],
	["Concept art was made with AI. The final art is hand-drawn.", MINOR],
	["部分宣传图片使用了AI生成", MINOR],
	[
		"The characters and backgrounds are not AI-generated. Only the music is.",
		SOME,
	],
	["Some textures were made with AI.", SOME],
	[
		"Placeholder voice lines were generated with AI and will be replaced.",
		SOME,
	],
	["The loading screen images are AI generated.", SOME],
	["Music, Sound Effects", SOME],
	[
		"The game does not generate any content during gameplay. Some icons were made with AI.",
		SOME,
	],
	["ゲーム内の一部の画像に生成AIを使用しています\u3002", SOME],
	["All art in this game is AI generated.", HEAVY],
	["The character art and backgrounds were made with Midjourney.", HEAVY],
	["NPC dialogue is generated by a language model while you play.", HEAVY],
	["本游戏的所有图片均由AI生成", HEAVY],
];

for (const [text, level] of cases) {
	test(`level ${level}: ${text || "(empty)"}`, () => {
		assert.equal(classify(text).level, level);
	});
}

test("kinds name what was made", () => {
	assert.deepEqual(classify("Music was generated with Suno.").kinds, [
		"music",
	]);
	assert.ok(
		classify(
			"NPCs answer you through ChatGPT in real time.",
		).kinds.includes("live"),
	);
});
